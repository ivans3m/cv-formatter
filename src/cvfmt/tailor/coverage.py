"""JD ↔ CV keyword coverage for dreamer prep mode."""

from __future__ import annotations

from cvfmt.models import CVDocument, canonical_section_key
from cvfmt.tailor.keywords import extract_keywords, tokenize
from cvfmt.tailor.score import score_text


def _cv_corpus(doc: CVDocument) -> str:
    chunks: list[str] = []
    for section in doc.renderable_sections:
        chunks.extend(section.paragraphs)
        chunks.extend(section.bullets)
        for entry in section.entries:
            chunks.append(entry.heading)
            chunks.extend(entry.bullets)
            for sr in entry.sub_roles:
                chunks.append(sr.title)
                chunks.extend(sr.bullets)
    if doc.facts_section:
        chunks.extend(doc.facts_section.bullets)
    return "\n".join(chunks)


def coverage_report(doc: CVDocument, jd_text: str) -> str:
    keywords = extract_keywords(jd_text)
    if not keywords:
        return "No extractable keywords from job description."

    corpus = _cv_corpus(doc)
    cv_tokens = set(tokenize(corpus))

    matched: list[str] = []
    missing: list[str] = []
    for kw in keywords[:40]:
        if kw in cv_tokens or kw in corpus.lower():
            matched.append(kw)
        else:
            missing.append(kw)

    lines = [
        "=== JD keyword coverage (top terms) ===",
        f"Matched ({len(matched)}): {', '.join(matched[:25]) or '(none)'}",
        f"Missing ({len(missing)}): {', '.join(missing[:25]) or '(none)'}",
        "",
        "=== Section relevance (0 = weak) ===",
    ]
    for section in doc.renderable_sections:
        if canonical_section_key(section.title) not in ("experience", "skills", "summary"):
            continue
        body = "\n".join(section.paragraphs + section.bullets)
        lines.append(f"  {section.title}: {score_text(body, keywords):.1f}")

    lines.extend(
        [
            "",
            "Dreamer prose is not generated by cvfmt. Use:",
            "  cvfmt tailor JOB.md --base cv-master.md --mode dreamer --prepare ./tailor-bundle/",
            "  or the skills/cv-tailor Agent Skill.",
        ]
    )
    return "\n".join(lines)